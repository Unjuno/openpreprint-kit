"""Public Git source bytes must match the versioned paper/data/code artifact.

HTTP transport is simulated; the actual immutable manifest and research TAR
are generated by the toolkit, not fabricated from expected output.
"""
from pathlib import Path
import sys
import unittest

import test_research_package

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'scripts'))


class SourceProvenanceTests(unittest.TestCase):
    def setUp(self):
        self.helper=test_research_package.ResearchBundleTests()
        self.helper.setUp(); self.addCleanup(self.helper.tearDown)
        self.helper.make_bundle()
        self.bundle=self.helper.bundle
        self.repo='example/science-paper'
        self.commit='a'*40
        from source_provenance import expected_source_files
        self.expected=expected_source_files(self.bundle)
        self.fetched=[]

    def fetch(self,path):
        self.fetched.append(path)
        return self.expected[path]

    def check(self,fetcher=None):
        from source_provenance import verify_source_snapshot
        return verify_source_snapshot(self.repo,self.commit,self.bundle,fetcher or self.fetch)

    def test_identical_public_git_snapshot_matches_paper_data_and_code(self):
        result=self.check()
        self.assertEqual(result['source_snapshot'],'VERIFIED_PUBLIC_GIT_BYTES')
        self.assertEqual(result['source_commit'],self.commit)
        self.assertEqual(result['checked_paths'],['analysis/fit.py','data/synthetic.csv','paper/paper.pdf'])
        self.assertEqual(self.fetched,result['checked_paths'])

    def test_different_paper_bytes_cannot_be_pass(self):
        with self.assertRaisesRegex(ValueError,'paper/paper.pdf'):
            self.check(lambda path:b'different PDF' if path=='paper/paper.pdf' else self.expected[path])

    def test_different_analysis_code_cannot_be_pass(self):
        with self.assertRaisesRegex(ValueError,'analysis/fit.py'):
            self.check(lambda path:b'print(999)' if path=='analysis/fit.py' else self.expected[path])

    def test_absent_source_file_fails_closed(self):
        def missing(path):
            if path=='data/synthetic.csv':raise FileNotFoundError(path)
            return self.expected[path]
        with self.assertRaisesRegex(ValueError,'data/synthetic.csv'):
            self.check(missing)

    def test_non_bytes_and_too_large_public_source_fail(self):
        for invalid in (None,'fake',b'0'*(25*1024*1024+1)):
            with self.subTest(type=type(invalid).__name__),self.assertRaises(ValueError):
                self.check(lambda path:invalid if path=='analysis/fit.py' else self.expected[path])

    def test_valid_empty_research_input_is_compared_not_rejected(self):
        import yaml
        with __import__('tempfile').TemporaryDirectory() as td:
            helper=test_research_package.ResearchBundleTests()
            helper.setUp()
            try:
                (helper.root/'data'/'empty.csv').write_bytes(b'')
                helper.configuration['public_assets'].append({
                    'path':'data/empty.csv','role':'dataset',
                    'description':'Intentionally empty measurement control',
                    'license':'CC0-1.0','public_confirmed':True})
                helper.save_config()
                helper.make_bundle()
                from source_provenance import expected_source_files,verify_source_snapshot
                expected=expected_source_files(helper.bundle)
                self.assertIn('data/empty.csv', expected)
                self.assertEqual(expected['data/empty.csv'], b'')
                self.assertEqual(verify_source_snapshot(self.repo,self.commit,helper.bundle,
                                    lambda path:expected[path])['checked_file_count'],4)
            finally:
                helper.tearDown()

    def test_commit_and_repo_must_be_explicit(self):
        from source_provenance import verify_source_snapshot
        for repo,commit in [('wrong url',self.commit),(self.repo,'main'),(self.repo,'0'*41)]:
            with self.subTest(repo=repo,commit=commit),self.assertRaises(ValueError):
                verify_source_snapshot(repo,commit,self.bundle,self.fetch)
            self.assertEqual(self.fetched,[])

    def test_untrusted_raw_redirect_is_rejected(self):
        from source_provenance import NoRedirect
        req=type('Req',(),{})()
        with self.assertRaises(ValueError):
            NoRedirect().redirect_request(req,None,302,'moved',{},'https://evil.invalid/steal')

    def test_fetch_source_requires_exact_commit_and_allowed_path(self):
        from source_provenance import fetch_source
        for path in ('../.env','paper/../../secret','https://evil.invalid','other/secret'):
            with self.subTest(path=path),self.assertRaises(ValueError):
                fetch_source(self.repo,self.commit,path)

if __name__=='__main__':unittest.main()
